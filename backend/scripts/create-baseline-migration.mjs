// Creates prisma/migrations/0_init from the current schema.prisma.
// Run once, on a machine with internet access:  npm run db:baseline
import { execSync } from 'node:child_process';
import { mkdirSync, writeFileSync, existsSync } from 'node:fs';

const dir = 'prisma/migrations/0_init';
if (existsSync(dir)) {
    console.log(`${dir} already exists - nothing to do.`);
    process.exit(0);
}
const sql = execSync('npx prisma migrate diff --from-empty --to-schema prisma/schema.prisma --script', {
    encoding: 'utf8',
    env: { ...process.env, DATABASE_URL: process.env.DATABASE_URL || 'postgresql://x:x@localhost:5432/x' },
});
mkdirSync(dir, { recursive: true });
writeFileSync(`${dir}/migration.sql`, sql);
writeFileSync('prisma/migrations/migration_lock.toml', '# Please do not edit this file manually\nprovider = "postgresql"\n');
console.log(`Created ${dir}/migration.sql (${sql.split('\n').length} lines).`);
console.log('\nNew installation : run  npm run db:deploy');
console.log('Existing database (already created with db push):');
console.log('  npx prisma migrate resolve --applied 0_init');
